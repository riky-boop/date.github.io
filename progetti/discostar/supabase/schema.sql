create table if not exists public.items (
  id         bigint generated by default as identity primary key,
  format     text not null check (format in ('LP', 'CD', 'DVD')),
  artist     text not null,
  title      text not null,
  year       int,
  genre      text not null default 'Altro',
  label      text not null default '',
  price      numeric(8, 2) not null default 0 check (price >= 0),
  stock      int not null default 0 check (stock >= 0),
  "isNew"    boolean not null default false,
  updated_at timestamptz not null default now()
);

-- Il negozio vende solo articoli nuovi: rimuove la colonna se creata da una versione precedente.
alter table public.items drop column if exists condition;

-- Chi può modificare il catalogo: aggiungi qui le email degli amministratori.
create table if not exists public.admins (
  email text primary key
);
alter table public.admins enable row level security; -- nessuna policy: non leggibile dal sito

-- insert into public.admins (email) values ('tua-email@esempio.it');

create or replace function public.is_admin()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (select 1 from public.admins where email = auth.jwt() ->> 'email');
$$;
grant execute on function public.is_admin() to anon, authenticated;

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists items_touch on public.items;
create trigger items_touch before update on public.items
  for each row execute function public.touch_updated_at();

-- Regole di accesso: tutti leggono, solo gli admin scrivono.
alter table public.items enable row level security;

drop policy if exists "Catalogo pubblico" on public.items;
create policy "Catalogo pubblico" on public.items
  for select to anon, authenticated using (true);

drop policy if exists "Solo admin inseriscono" on public.items;
create policy "Solo admin inseriscono" on public.items
  for insert to authenticated with check (public.is_admin());

drop policy if exists "Solo admin modificano" on public.items;
create policy "Solo admin modificano" on public.items
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Solo admin eliminano" on public.items;
create policy "Solo admin eliminano" on public.items
  for delete to authenticated using (public.is_admin());
